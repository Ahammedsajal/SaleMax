-- Tenant-scoped sellable variants, branch inventory and guest storefront orders.
-- Orders reserve inventory at checkout; payment is tracked separately.
CREATE TABLE sx_retail_variants (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  product_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  sku VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  name_en VARCHAR(160) NOT NULL,
  name_ar VARCHAR(160) NOT NULL DEFAULT '',
  price_minor BIGINT UNSIGNED NOT NULL,
  currency CHAR(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'QAR',
  status ENUM('active','retired') NOT NULL DEFAULT 'active',
  revision INT UNSIGNED NOT NULL DEFAULT 1,
  created_by_identity_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  updated_by_identity_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_sx_retail_variant_tenant_id (tenant_id,id),
  UNIQUE KEY uq_sx_retail_variant_sku (tenant_id,sku),
  KEY ix_sx_retail_variant_product (tenant_id,product_id,status),
  CONSTRAINT fk_sx_retail_variant_tenant FOREIGN KEY (tenant_id) REFERENCES sx_tenants(id),
  CONSTRAINT fk_sx_retail_variant_product FOREIGN KEY (tenant_id,product_id) REFERENCES sx_product_catalog(tenant_id,id),
  CONSTRAINT fk_sx_retail_variant_creator FOREIGN KEY (created_by_identity_id) REFERENCES sx_identities(id),
  CONSTRAINT fk_sx_retail_variant_updater FOREIGN KEY (updated_by_identity_id) REFERENCES sx_identities(id),
  CONSTRAINT ck_sx_retail_variant_price CHECK (price_minor <= 999999999999)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE sx_retail_stock (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  variant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  branch_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  on_hand INT UNSIGNED NOT NULL DEFAULT 0,
  reserved INT UNSIGNED NOT NULL DEFAULT 0,
  revision INT UNSIGNED NOT NULL DEFAULT 1,
  updated_by_identity_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_sx_retail_stock_branch (tenant_id,variant_id,branch_id),
  KEY ix_sx_retail_stock_branch (tenant_id,branch_id,variant_id),
  CONSTRAINT fk_sx_retail_stock_variant FOREIGN KEY (tenant_id,variant_id) REFERENCES sx_retail_variants(tenant_id,id),
  CONSTRAINT fk_sx_retail_stock_branch FOREIGN KEY (tenant_id,branch_id) REFERENCES sx_tenant_branches(tenant_id,id),
  CONSTRAINT fk_sx_retail_stock_updater FOREIGN KEY (updated_by_identity_id) REFERENCES sx_identities(id),
  CONSTRAINT ck_sx_retail_stock_reserved CHECK (reserved <= on_hand)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE sx_retail_orders (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  branch_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  order_reference VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  request_key_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  payload_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  guest_access_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  customer_name VARCHAR(120) NOT NULL,
  customer_email VARCHAR(254) NOT NULL DEFAULT '',
  customer_mobile VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  fulfillment_mode ENUM('pickup','delivery') NOT NULL,
  delivery_address VARCHAR(1000) NOT NULL DEFAULT '',
  payment_method ENUM('cash_on_delivery','bank_transfer') NOT NULL,
  payment_status ENUM('unpaid','pending_verification','paid','refunded') NOT NULL DEFAULT 'unpaid',
  currency CHAR(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  subtotal_minor BIGINT UNSIGNED NOT NULL,
  status ENUM('confirmed','preparing','ready','out_for_delivery','completed','cancelled','return_requested','returned') NOT NULL DEFAULT 'confirmed',
  return_reason VARCHAR(1000) NULL,
  revision INT UNSIGNED NOT NULL DEFAULT 1,
  consented_at DATETIME(3) NOT NULL,
  consent_version VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_sx_retail_order_tenant_id (tenant_id,id),
  UNIQUE KEY uq_sx_retail_order_reference (tenant_id,order_reference),
  UNIQUE KEY uq_sx_retail_order_request (tenant_id,request_key_hash),
  KEY ix_sx_retail_order_queue (tenant_id,status,created_at),
  CONSTRAINT fk_sx_retail_order_tenant FOREIGN KEY (tenant_id) REFERENCES sx_tenants(id),
  CONSTRAINT fk_sx_retail_order_branch FOREIGN KEY (tenant_id,branch_id) REFERENCES sx_tenant_branches(tenant_id,id),
  CONSTRAINT ck_sx_retail_order_total CHECK (subtotal_minor <= 999999999999)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE sx_retail_order_items (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  order_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  variant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  sku_snapshot VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  name_en_snapshot VARCHAR(160) NOT NULL,
  name_ar_snapshot VARCHAR(160) NOT NULL DEFAULT '',
  quantity SMALLINT UNSIGNED NOT NULL,
  unit_price_minor BIGINT UNSIGNED NOT NULL,
  currency CHAR(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  line_total_minor BIGINT UNSIGNED NOT NULL,
  PRIMARY KEY (id),
  KEY ix_sx_retail_order_item_order (tenant_id,order_id),
  CONSTRAINT fk_sx_retail_item_order FOREIGN KEY (tenant_id,order_id) REFERENCES sx_retail_orders(tenant_id,id),
  CONSTRAINT fk_sx_retail_item_variant FOREIGN KEY (tenant_id,variant_id) REFERENCES sx_retail_variants(tenant_id,id),
  CONSTRAINT ck_sx_retail_item_quantity CHECK (quantity > 0),
  CONSTRAINT ck_sx_retail_item_total CHECK (line_total_minor <= 999999999999)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
