CREATE TABLE sx_recruitment_applications (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  submission_hash BINARY(32) NOT NULL,
  reference_code VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  full_name VARCHAR(160) NOT NULL,
  mobile VARCHAR(40) NOT NULL,
  normalized_mobile VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  email VARCHAR(254) NULL,
  english_level ENUM('proficient','native','intermediate','basic') NOT NULL,
  hindi_level ENUM('fluent','conversational','basic','none') NOT NULL DEFAULT 'none',
  experience_years TINYINT UNSIGNED NOT NULL,
  crm_saas_experience TEXT NOT NULL,
  availability ENUM('part_time','full_time','either') NOT NULL,
  cv_storage_key VARCHAR(320) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  cv_file_name VARCHAR(180) NOT NULL,
  cv_mime_type VARCHAR(100) NOT NULL,
  cv_bytes INT UNSIGNED NOT NULL,
  cv_sha256 BINARY(32) NOT NULL,
  linked_contact_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  linked_lead_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  source_channel ENUM('public_form','whatsapp') NOT NULL DEFAULT 'public_form',
  source_reference VARCHAR(160) NULL,
  status ENUM('new','reviewing','shortlisted','interview','rejected','hired','archived') NOT NULL DEFAULT 'new',
  consent_text VARCHAR(500) NOT NULL,
  consented_at DATETIME(3) NOT NULL,
  revision INT UNSIGNED NOT NULL DEFAULT 1,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY sx_recruitment_submission_idempotency (tenant_id, submission_hash),
  UNIQUE KEY sx_recruitment_reference (tenant_id, reference_code),
  UNIQUE KEY sx_recruitment_tenant_id (tenant_id, id),
  KEY sx_recruitment_inbox (tenant_id, status, created_at),
  KEY sx_recruitment_phone (tenant_id, normalized_mobile),
  CONSTRAINT sx_recruitment_tenant_fk FOREIGN KEY (tenant_id) REFERENCES sx_tenants(id) ON DELETE CASCADE,
  KEY sx_recruitment_linked_contact (linked_contact_id),
  KEY sx_recruitment_linked_lead (linked_lead_id),
  CONSTRAINT sx_recruitment_experience_years CHECK (experience_years <= 50)
);

CREATE TABLE sx_recruitment_rate_limits (
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  visitor_hash BINARY(32) NOT NULL,
  window_started_at DATETIME(3) NOT NULL,
  attempts INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (tenant_id, visitor_hash),
  CONSTRAINT sx_recruitment_rate_tenant_fk FOREIGN KEY (tenant_id) REFERENCES sx_tenants(id) ON DELETE CASCADE
);
