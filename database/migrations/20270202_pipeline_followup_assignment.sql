CREATE TABLE sx_pipeline_followup_assignment_settings (
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  uid_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  enabled TINYINT(1) NOT NULL DEFAULT 0,
  timezone VARCHAR(64) NOT NULL DEFAULT 'Asia/Qatar',
  send_time CHAR(5) NOT NULL DEFAULT '09:00',
  updated_by_identity_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (tenant_id),
  UNIQUE KEY uq_pipeline_followup_assignment_uid (uid_hash),
  KEY idx_pipeline_followup_assignment_daily (enabled, send_time),
  CONSTRAINT fk_pipeline_followup_assignment_settings_tenant FOREIGN KEY (tenant_id) REFERENCES sx_tenants(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE sx_pipeline_followup_assignment_runs (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  uid_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  local_date DATE NOT NULL,
  timezone VARCHAR(64) NOT NULL,
  run_mode ENUM('manual','scheduled') NOT NULL,
  status ENUM('planning','assigning','complete','partial','failed') NOT NULL DEFAULT 'planning',
  deliver_at DATETIME(3) NOT NULL,
  high_count INT UNSIGNED NOT NULL DEFAULT 0,
  warm_count INT UNSIGNED NOT NULL DEFAULT 0,
  candidate_count INT UNSIGNED NOT NULL DEFAULT 0,
  existing_assigned_count INT UNSIGNED NOT NULL DEFAULT 0,
  review_excluded_count INT UNSIGNED NOT NULL DEFAULT 0,
  waiting_72h_count INT UNSIGNED NOT NULL DEFAULT 0,
  planned_count INT UNSIGNED NOT NULL DEFAULT 0,
  assigned_count INT UNSIGNED NOT NULL DEFAULT 0,
  skipped_count INT UNSIGNED NOT NULL DEFAULT 0,
  failed_count INT UNSIGNED NOT NULL DEFAULT 0,
  notification_count INT UNSIGNED NOT NULL DEFAULT 0,
  no_phone_agent_count INT UNSIGNED NOT NULL DEFAULT 0,
  last_error_code VARCHAR(64) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  completed_at DATETIME(3) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_pipeline_followup_assignment_run_day (tenant_id, local_date),
  KEY idx_pipeline_followup_assignment_run_queue (status, created_at),
  CONSTRAINT fk_pipeline_followup_assignment_run_tenant FOREIGN KEY (tenant_id) REFERENCES sx_tenants(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE sx_pipeline_followup_assignment_items (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  run_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  lead_id CHAR(36) NOT NULL,
  agent_id INT NOT NULL,
  priority ENUM('high','warm') NOT NULL,
  days_waiting INT UNSIGNED NOT NULL DEFAULT 0,
  status ENUM('planned','processing','assigned','skipped','failed') NOT NULL DEFAULT 'planned',
  attempts TINYINT UNSIGNED NOT NULL DEFAULT 0,
  lease_token CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  lease_until DATETIME(3) NULL,
  retry_after DATETIME(3) NULL,
  last_error_code VARCHAR(64) NULL,
  assigned_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_pipeline_followup_assignment_item (run_id, lead_id),
  KEY idx_pipeline_followup_assignment_items_claim (tenant_id, run_id, status, retry_after, id),
  KEY idx_pipeline_followup_assignment_items_agent (tenant_id, run_id, agent_id, status),
  CONSTRAINT fk_pipeline_followup_assignment_item_run FOREIGN KEY (run_id) REFERENCES sx_pipeline_followup_assignment_runs(id),
  CONSTRAINT fk_pipeline_followup_assignment_item_tenant FOREIGN KEY (tenant_id) REFERENCES sx_tenants(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE sx_pipeline_followup_assignment_outbox (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  run_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  recipient_type ENUM('agent','user') NOT NULL,
  recipient_id VARCHAR(191) NOT NULL,
  phone_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  message_text VARCHAR(1800) NOT NULL,
  available_at DATETIME(3) NOT NULL,
  status ENUM('queued','sending','accepted','unknown','failed','cancelled') NOT NULL DEFAULT 'queued',
  attempts TINYINT UNSIGNED NOT NULL DEFAULT 0,
  lease_token CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  lease_until DATETIME(3) NULL,
  provider_message_id VARCHAR(191) NULL,
  last_error_code VARCHAR(64) NULL,
  sent_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_pipeline_followup_assignment_digest (tenant_id, run_id, phone_hash),
  KEY idx_pipeline_followup_assignment_outbox (tenant_id, status, available_at, id),
  CONSTRAINT fk_pipeline_followup_assignment_outbox_run FOREIGN KEY (run_id) REFERENCES sx_pipeline_followup_assignment_runs(id),
  CONSTRAINT fk_pipeline_followup_assignment_outbox_tenant FOREIGN KEY (tenant_id) REFERENCES sx_tenants(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
