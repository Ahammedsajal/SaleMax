-- Guest restaurant orders are requests until a business member accepts them.
-- The menu, modifier labels and prices are snapshotted per order line.
CREATE TABLE sx_restaurant_orders (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  branch_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  order_reference VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  request_key_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  payload_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  guest_access_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  customer_name VARCHAR(120) NOT NULL,
  customer_email VARCHAR(254) NOT NULL DEFAULT '',
  customer_mobile VARCHAR(20) NOT NULL DEFAULT '',
  fulfillment_mode ENUM('pickup','delivery') NOT NULL,
  delivery_address VARCHAR(1000) NOT NULL DEFAULT '',
  payment_method ENUM('cash_on_delivery','bank_transfer') NOT NULL,
  payment_status ENUM('unpaid','pending_verification','verified','refunded') NOT NULL,
  currency CHAR(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  subtotal_minor BIGINT UNSIGNED NOT NULL,
  status ENUM('requested','confirmed','preparing','ready','out_for_delivery','completed','cancelled','rejected') NOT NULL DEFAULT 'requested',
  revision INT UNSIGNED NOT NULL DEFAULT 1,
  consented_at DATETIME(3) NOT NULL,
  consent_version VARCHAR(64) NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_sx_restaurant_order_tenant_id (tenant_id,id),
  UNIQUE KEY uq_sx_restaurant_order_reference (tenant_id,order_reference),
  UNIQUE KEY uq_sx_restaurant_order_request (tenant_id,request_key_hash),
  KEY ix_sx_restaurant_order_queue (tenant_id,branch_id,status,created_at),
  CONSTRAINT fk_sx_restaurant_order_tenant FOREIGN KEY (tenant_id) REFERENCES sx_tenants(id),
  CONSTRAINT fk_sx_restaurant_order_branch FOREIGN KEY (tenant_id,branch_id) REFERENCES sx_tenant_branches(tenant_id,id),
  CONSTRAINT ck_sx_restaurant_order_total CHECK (subtotal_minor <= 999999999999)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE sx_restaurant_order_items (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  order_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  menu_item_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  product_code_snapshot VARCHAR(80) NOT NULL,
  product_name_en_snapshot VARCHAR(160) NOT NULL,
  product_name_ar_snapshot VARCHAR(160) NOT NULL DEFAULT '',
  quantity TINYINT UNSIGNED NOT NULL,
  base_price_minor BIGINT UNSIGNED NOT NULL,
  unit_price_minor BIGINT UNSIGNED NOT NULL,
  modifiers_snapshot JSON NOT NULL,
  line_total_minor BIGINT UNSIGNED NOT NULL,
  currency CHAR(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_sx_restaurant_order_item_tenant_id (tenant_id,id),
  KEY ix_sx_restaurant_order_item_order (tenant_id,order_id),
  CONSTRAINT fk_sx_restaurant_order_item_order FOREIGN KEY (tenant_id,order_id) REFERENCES sx_restaurant_orders(tenant_id,id),
  CONSTRAINT fk_sx_restaurant_order_item_menu FOREIGN KEY (tenant_id,menu_item_id) REFERENCES sx_restaurant_menu_items(tenant_id,id),
  CONSTRAINT ck_sx_restaurant_order_item_quantity CHECK (quantity BETWEEN 1 AND 20),
  CONSTRAINT ck_sx_restaurant_order_item_total CHECK (line_total_minor <= 999999999999)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
