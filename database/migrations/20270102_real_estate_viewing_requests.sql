-- Guest viewing requests are requests, not reserved appointments. Confirmation
-- is deliberately absent until the business can reserve an actual resource.
CREATE TABLE sx_real_estate_viewing_requests (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  property_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  lead_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  reference_code VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  contact_name VARCHAR(120) NOT NULL,
  phone VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT '',
  email VARCHAR(254) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT '',
  preferred_date DATE NULL,
  message VARCHAR(1000) NOT NULL DEFAULT '',
  consent_text_en VARCHAR(500) NOT NULL,
  consent_text_ar VARCHAR(500) NOT NULL,
  consented_at DATETIME(3) NOT NULL,
  idempotency_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  visitor_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  status ENUM('requested','contacted','declined','cancelled') NOT NULL DEFAULT 'requested',
  revision INT UNSIGNED NOT NULL DEFAULT 1,
  reviewed_by_identity_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_sx_re_viewing_request_tenant_id (tenant_id,id),
  UNIQUE KEY uq_sx_re_viewing_request_reference (tenant_id,reference_code),
  UNIQUE KEY uq_sx_re_viewing_request_idempotency (tenant_id,idempotency_hash),
  KEY ix_sx_re_viewing_request_queue (tenant_id,status,created_at,id),
  KEY ix_sx_re_viewing_request_property (tenant_id,property_id,status,created_at),
  KEY ix_sx_re_viewing_request_rate (tenant_id,visitor_hash,created_at),
  CONSTRAINT fk_sx_re_viewing_request_property FOREIGN KEY (tenant_id,property_id) REFERENCES sx_real_estate_properties(tenant_id,id),
  CONSTRAINT fk_sx_re_viewing_request_tenant FOREIGN KEY (tenant_id) REFERENCES sx_tenants(id),
  CONSTRAINT fk_sx_re_viewing_request_reviewer FOREIGN KEY (reviewed_by_identity_id) REFERENCES sx_identities(id),
  CONSTRAINT ck_sx_re_viewing_request_revision CHECK (revision > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
