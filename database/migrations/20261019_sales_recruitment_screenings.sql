CREATE TABLE sx_recruitment_screenings (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  channel_kind ENUM('whatsapp_meta','whatsapp_qr') NOT NULL,
  channel_ref VARCHAR(160) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  conversation_id VARCHAR(999) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
  conversation_hash BINARY(32) NOT NULL,
  mobile VARCHAR(40) NOT NULL,
  normalized_mobile VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  sender_name VARCHAR(160) NULL,
  answers JSON NOT NULL,
  consent_text VARCHAR(500) NOT NULL,
  consented_at DATETIME(3) NOT NULL,
  completed_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY sx_recruitment_screening_conversation (tenant_id,channel_kind,channel_ref,conversation_hash),
  KEY sx_recruitment_screening_inbox (tenant_id,updated_at),
  KEY sx_recruitment_screening_phone (tenant_id,normalized_mobile),
  CONSTRAINT sx_recruitment_screening_tenant_fk FOREIGN KEY (tenant_id) REFERENCES sx_tenants(id) ON DELETE CASCADE
);
