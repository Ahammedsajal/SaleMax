CREATE TABLE sx_tenant_owner_transfers (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  legacy_user_id INT NOT NULL,
  legacy_uid_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  prior_identity_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  prior_membership_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  recipient_email_normalized VARCHAR(254) NOT NULL,
  status ENUM('pending','accepted','cancelled','expired') NOT NULL DEFAULT 'pending',
  reserved_recipient_email VARCHAR(254) GENERATED ALWAYS AS (CASE WHEN status='pending' THEN recipient_email_normalized ELSE NULL END) PERSISTENT,
  token_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  invited_by_identity_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  reason VARCHAR(1000) NOT NULL,
  expires_at DATETIME(3) NOT NULL,
  accepted_at DATETIME(3) NULL,
  new_identity_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  new_membership_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_sx_owner_transfer_token (token_hash),
  UNIQUE KEY uq_sx_pending_owner_transfer_email (tenant_id,reserved_recipient_email),
  KEY idx_sx_owner_transfer_status (tenant_id,status,expires_at),
  CONSTRAINT fk_sx_owner_transfer_tenant FOREIGN KEY (tenant_id) REFERENCES sx_tenants(id),
  CONSTRAINT fk_sx_owner_transfer_old_owner FOREIGN KEY (tenant_id,prior_membership_id,prior_identity_id) REFERENCES sx_memberships(tenant_id,id,identity_id),
  CONSTRAINT fk_sx_owner_transfer_new_owner FOREIGN KEY (tenant_id,new_membership_id,new_identity_id) REFERENCES sx_memberships(tenant_id,id,identity_id),
  CONSTRAINT fk_sx_owner_transfer_actor FOREIGN KEY (invited_by_identity_id) REFERENCES sx_identities(id),
  CONSTRAINT ck_sx_owner_transfer_result CHECK ((status='accepted' AND accepted_at IS NOT NULL AND new_identity_id IS NOT NULL AND new_membership_id IS NOT NULL) OR (status<>'accepted' AND accepted_at IS NULL AND new_identity_id IS NULL AND new_membership_id IS NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE utf8mb4_bin;
