-- Private Real Estate v2. Requirements reference existing tenant Pipeline leads
-- by the verified legacy owner hash; no duplicate customer/contact data is kept.
CREATE TABLE sx_real_estate_requirements (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  legacy_uid_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  lead_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  transaction_type ENUM('sale','rent') NOT NULL,
  property_type ENUM('any','apartment','house','villa','townhouse','land','commercial','office','warehouse','other') NOT NULL DEFAULT 'any',
  min_price_minor BIGINT UNSIGNED NULL,
  max_price_minor BIGINT UNSIGNED NULL,
  currency CHAR(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'QAR',
  min_area_sqm DECIMAL(12,2) NULL,
  max_area_sqm DECIMAL(12,2) NULL,
  min_bedrooms SMALLINT UNSIGNED NULL,
  preferred_city VARCHAR(100) NULL,
  assigned_membership_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  status ENUM('open','matched','closed') NOT NULL DEFAULT 'open',
  revision INT UNSIGNED NOT NULL DEFAULT 1,
  created_by_identity_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  updated_by_identity_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_sx_real_estate_requirement_tenant_id (tenant_id,id),
  UNIQUE KEY uq_sx_real_estate_requirement_lead (tenant_id,legacy_uid_hash,lead_id),
  KEY idx_sx_real_estate_requirement_work (tenant_id,status,transaction_type,property_type,preferred_city),
  KEY idx_sx_real_estate_requirement_assignee (tenant_id,assigned_membership_id,status,updated_at),
  CONSTRAINT fk_sx_real_estate_requirement_tenant FOREIGN KEY (tenant_id) REFERENCES sx_tenants(id),
  CONSTRAINT fk_sx_real_estate_requirement_created_by FOREIGN KEY (tenant_id,created_by_identity_id) REFERENCES sx_memberships(tenant_id,identity_id),
  CONSTRAINT fk_sx_real_estate_requirement_updated_by FOREIGN KEY (tenant_id,updated_by_identity_id) REFERENCES sx_memberships(tenant_id,identity_id),
  CONSTRAINT fk_sx_real_estate_requirement_assignee FOREIGN KEY (tenant_id,assigned_membership_id) REFERENCES sx_memberships(tenant_id,id),
  CONSTRAINT ck_sx_real_estate_requirement_price CHECK (min_price_minor IS NULL OR min_price_minor <= 999999999999),
  CONSTRAINT ck_sx_real_estate_requirement_price_range CHECK (min_price_minor IS NULL OR max_price_minor IS NULL OR min_price_minor <= max_price_minor),
  CONSTRAINT ck_sx_real_estate_requirement_area CHECK ((min_area_sqm IS NULL OR min_area_sqm > 0) AND (max_area_sqm IS NULL OR max_area_sqm > 0)),
  CONSTRAINT ck_sx_real_estate_requirement_area_range CHECK (min_area_sqm IS NULL OR max_area_sqm IS NULL OR min_area_sqm <= max_area_sqm),
  CONSTRAINT ck_sx_real_estate_requirement_revision CHECK (revision > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
