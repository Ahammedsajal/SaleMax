CREATE TABLE sx_chatbot_mockup_turns (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  conversation_key CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  event_key CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  channel_kind ENUM('whatsapp_qr','whatsapp_meta') NOT NULL,
  channel_ref VARCHAR(191) NOT NULL,
  chat_id VARCHAR(255) NOT NULL,
  sender_label VARCHAR(160) NOT NULL,
  message_type VARCHAR(40) NOT NULL,
  customer_text TEXT NOT NULL,
  status ENUM('queued','processing','ready','review','failed') NOT NULL DEFAULT 'queued',
  reply_text TEXT NULL,
  state_json JSON NULL,
  route VARCHAR(64) NULL,
  reason VARCHAR(100) NULL,
  profile_revision INT UNSIGNED NULL,
  attempts TINYINT UNSIGNED NOT NULL DEFAULT 0,
  lease_token CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  lease_until DATETIME(3) NULL,
  available_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_mockup_inbound (tenant_id,event_key),
  KEY idx_mockup_conversation (tenant_id,conversation_key,id),
  KEY idx_mockup_queue (tenant_id,status,available_at,id),
  KEY idx_mockup_retention (tenant_id,created_at,id),
  CONSTRAINT fk_mockup_tenant FOREIGN KEY (tenant_id) REFERENCES sx_tenants(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
