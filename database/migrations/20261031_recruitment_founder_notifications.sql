CREATE TABLE sx_recruitment_founder_notifications (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  profile_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  channel_kind ENUM('whatsapp_meta','whatsapp_qr') NOT NULL,
  channel_ref VARCHAR(160) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  conversation_id VARCHAR(999) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  inbound_message_id VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  payload JSON NULL,
  status ENUM('queued','processing','sent','failed') NOT NULL DEFAULT 'queued',
  attempt_count SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  available_at DATETIME(3) NOT NULL,
  lease_owner VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NULL,
  lease_expires_at DATETIME(3) NULL,
  provider_message_id VARCHAR(191) CHARACTER SET ascii COLLATE ascii_bin NULL,
  last_error_code VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  sent_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_sx_recruitment_founder_inbound (tenant_id,inbound_message_id),
  KEY idx_sx_recruitment_founder_queue (status,available_at,created_at,id),
  CONSTRAINT fk_sx_recruitment_founder_tenant FOREIGN KEY (tenant_id) REFERENCES sx_tenants(id),
  CONSTRAINT fk_sx_recruitment_founder_profile FOREIGN KEY (tenant_id,profile_id) REFERENCES sx_chatbot_profiles(tenant_id,id) ON DELETE CASCADE,
  CONSTRAINT ck_sx_recruitment_founder_lease CHECK ((status='processing' AND lease_owner IS NOT NULL AND lease_expires_at IS NOT NULL) OR (status<>'processing' AND lease_owner IS NULL AND lease_expires_at IS NULL))
);
