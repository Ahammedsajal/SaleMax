-- Tenant-owned relationship directory and explicit authority to market inventory.
CREATE TABLE sx_real_estate_contacts (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  contact_type ENUM('owner','property_manager','brokerage','partner') NOT NULL,
  display_name VARCHAR(180) NOT NULL,
  company_name VARCHAR(180) NULL,
  email VARCHAR(254) NULL,
  phone VARCHAR(40) NULL,
  license_number VARCHAR(100) NULL,
  license_expires_on DATE NULL,
  partner_tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  notes VARCHAR(1000) NULL,
  status ENUM('active','inactive') NOT NULL DEFAULT 'active',
  revision INT UNSIGNED NOT NULL DEFAULT 1,
  created_by_identity_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY(id),
  UNIQUE KEY uq_sx_re_contact_tenant_id(tenant_id,id),
  KEY idx_sx_re_contact_type(tenant_id,contact_type,status,display_name),
  KEY idx_sx_re_partner_tenant(partner_tenant_id,status),
  CONSTRAINT fk_sx_re_contact_tenant FOREIGN KEY(tenant_id) REFERENCES sx_tenants(id),
  CONSTRAINT fk_sx_re_contact_creator FOREIGN KEY(created_by_identity_id) REFERENCES sx_identities(id),
  CONSTRAINT fk_sx_re_contact_creator_member FOREIGN KEY(tenant_id,created_by_identity_id) REFERENCES sx_memberships(tenant_id,identity_id),
  CONSTRAINT fk_sx_re_contact_partner FOREIGN KEY(partner_tenant_id) REFERENCES sx_tenants(id)
);

CREATE TABLE sx_real_estate_agreements (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  contact_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  agreement_type ENUM('owner_mandate','management','brokerage','referral') NOT NULL,
  status ENUM('draft','active','expired','revoked') NOT NULL DEFAULT 'draft',
  starts_on DATE NOT NULL,
  ends_on DATE NOT NULL,
  exclusive TINYINT(1) NOT NULL DEFAULT 0,
  may_advertise TINYINT(1) NOT NULL DEFAULT 0,
  may_conduct_viewings TINYINT(1) NOT NULL DEFAULT 0,
  may_refer_agents TINYINT(1) NOT NULL DEFAULT 0,
  media_approved TINYINT(1) NOT NULL DEFAULT 0,
  description_approved TINYINT(1) NOT NULL DEFAULT 0,
  permitted_channels JSON NOT NULL,
  commission_basis ENUM('first_month_rent','percentage','fixed','none') NOT NULL DEFAULT 'first_month_rent',
  commission_value DECIMAL(12,4) NULL,
  commission_payer ENUM('owner','manager','brokerage','tenant','other') NULL,
  commission_trigger VARCHAR(120) NULL,
  commission_exceptions VARCHAR(1000) NULL,
  document_name VARCHAR(255) NULL,
  document_reference VARCHAR(500) NULL,
  revoked_at TIMESTAMP(3) NULL,
  revoked_by_identity_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  created_by_identity_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  revision INT UNSIGNED NOT NULL DEFAULT 1,
  PRIMARY KEY(id),
  UNIQUE KEY uq_sx_re_agreement_tenant_id(tenant_id,id),
  KEY idx_sx_re_agreement_validity(tenant_id,status,starts_on,ends_on),
  KEY idx_sx_re_agreement_contact(tenant_id,contact_id,status),
  CONSTRAINT fk_sx_re_agreement_tenant FOREIGN KEY(tenant_id) REFERENCES sx_tenants(id),
  CONSTRAINT fk_sx_re_agreement_contact FOREIGN KEY(tenant_id,contact_id) REFERENCES sx_real_estate_contacts(tenant_id,id),
  CONSTRAINT fk_sx_re_agreement_creator FOREIGN KEY(tenant_id,created_by_identity_id) REFERENCES sx_memberships(tenant_id,identity_id),
  CONSTRAINT fk_sx_re_agreement_revoker FOREIGN KEY(revoked_by_identity_id) REFERENCES sx_identities(id),
  CONSTRAINT ck_sx_re_agreement_dates CHECK(ends_on >= starts_on),
  CONSTRAINT ck_sx_re_agreement_value CHECK(commission_value IS NULL OR commission_value >= 0)
);

CREATE TABLE sx_real_estate_agreement_units (
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  agreement_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  unit_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  PRIMARY KEY(tenant_id,agreement_id,unit_id),
  KEY idx_sx_re_agreement_units_unit(tenant_id,unit_id,agreement_id),
  CONSTRAINT fk_sx_re_agreement_units_agreement FOREIGN KEY(tenant_id,agreement_id) REFERENCES sx_real_estate_agreements(tenant_id,id),
  CONSTRAINT fk_sx_re_agreement_units_unit FOREIGN KEY(tenant_id,unit_id) REFERENCES sx_real_estate_units(tenant_id,id)
);

CREATE TABLE sx_real_estate_agreement_documents (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  agreement_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  original_name VARCHAR(240) NOT NULL,
  file_size_bytes BIGINT UNSIGNED NOT NULL,
  sha256_hex CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  created_by_identity_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  deleted_at DATETIME(3) NULL,
  PRIMARY KEY(id),
  UNIQUE KEY uq_sx_re_agreement_document_tenant_id(tenant_id,id),
  KEY idx_sx_re_agreement_document(tenant_id,agreement_id,deleted_at,created_at),
  CONSTRAINT fk_sx_re_agreement_document_agreement FOREIGN KEY(tenant_id,agreement_id) REFERENCES sx_real_estate_agreements(tenant_id,id),
  CONSTRAINT fk_sx_re_agreement_document_creator FOREIGN KEY(tenant_id,created_by_identity_id) REFERENCES sx_memberships(tenant_id,identity_id),
  CONSTRAINT ck_sx_re_agreement_document_size CHECK(file_size_bytes BETWEEN 8 AND 104857600)
);
