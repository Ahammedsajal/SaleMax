CREATE TABLE sx_invoice_communication_documents (
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  document_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  document_type ENUM('generated','formal') NOT NULL DEFAULT 'generated',
  generated_document_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  formal_invoice_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  reminders_opted_out TINYINT(1) NOT NULL DEFAULT 0,
  scan_error_code VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NULL,
  next_scan_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  created_by_identity_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (tenant_id,document_id),
  KEY idx_invoice_communication_scan (next_scan_at,tenant_id,document_id),
  UNIQUE KEY uq_invoice_communication_generated (tenant_id,generated_document_id),
  UNIQUE KEY uq_invoice_communication_formal (tenant_id,formal_invoice_id),
  CONSTRAINT fk_invoice_communication_generated FOREIGN KEY (tenant_id,generated_document_id) REFERENCES sx_invoice_generator_documents(tenant_id,id),
  CONSTRAINT fk_invoice_communication_formal FOREIGN KEY (tenant_id,formal_invoice_id) REFERENCES sx_training_invoices(tenant_id,id),
  CONSTRAINT ck_invoice_communication_source CHECK ((document_type='generated' AND generated_document_id=document_id AND generated_document_id IS NOT NULL AND formal_invoice_id IS NULL) OR (document_type='formal' AND formal_invoice_id=document_id AND formal_invoice_id IS NOT NULL AND generated_document_id IS NULL)),
  CONSTRAINT fk_invoice_communication_actor FOREIGN KEY (created_by_identity_id) REFERENCES sx_identities(id),
  CONSTRAINT ck_invoice_communication_optout CHECK (reminders_opted_out IN (0,1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE sx_invoice_customer_jobs (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  document_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  document_revision INT UNSIGNED NOT NULL,
  idempotency_key VARCHAR(191) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  kind ENUM('invoice','upcoming','due','overdue') NOT NULL,
  channel ENUM('email','whatsapp') NOT NULL,
  recipient_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  installment_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  sequence_number INT UNSIGNED NULL,
  scheduled_date DATE NULL,
  due_date DATE NULL,
  amount_minor BIGINT UNSIGNED NULL,
  status ENUM('queued','processing','accepted','retry','blocked','failed','unknown','suppressed') NOT NULL DEFAULT 'queued',
  attempts INT UNSIGNED NOT NULL DEFAULT 0,
  available_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  lease_owner VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NULL,
  lease_expires_at DATETIME(3) NULL,
  send_started_at DATETIME(3) NULL,
  settings_revision INT UNSIGNED NULL,
  subject_snapshot VARCHAR(500) NULL,
  body_snapshot TEXT NULL,
  provider_message_id VARCHAR(191) NULL,
  error_code VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NULL,
  completed_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_invoice_customer_job (tenant_id,idempotency_key),
  KEY idx_invoice_customer_job_ready (status,available_at,id),
  KEY idx_invoice_customer_job_document (tenant_id,document_id,created_at),
  CONSTRAINT fk_invoice_customer_job_doc FOREIGN KEY (tenant_id,document_id) REFERENCES sx_invoice_communication_documents(tenant_id,document_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE sx_invoice_customer_access (
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  document_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  document_revision INT UNSIGNED NOT NULL,
  token_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  token_ciphertext VARBINARY(128) NOT NULL,
  token_iv BINARY(12) NOT NULL,
  token_tag BINARY(16) NOT NULL,
  snapshot_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  expires_at DATETIME(3) NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (tenant_id,document_id,document_revision),
  UNIQUE KEY uq_invoice_customer_access_token (token_hash),
  CONSTRAINT fk_invoice_customer_access_doc FOREIGN KEY (tenant_id,document_id) REFERENCES sx_invoice_communication_documents(tenant_id,document_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
