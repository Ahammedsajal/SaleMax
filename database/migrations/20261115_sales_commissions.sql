  lead_uid_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  lead_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  seller_membership_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
