  CONSTRAINT fk_sx_sales_deals_seller FOREIGN KEY (tenant_id,seller_membership_id) REFERENCES sx_memberships(tenant_id,id),
  CONSTRAINT fk_sx_sales_deals_manager FOREIGN KEY (tenant_id,manager_membership_id) REFERENCES sx_memberships(tenant_id,id),
  CONSTRAINT fk_sx_sales_deals_leader FOREIGN KEY (tenant_id,team_leader_membership_id) REFERENCES sx_memberships(tenant_id,id),
  CONSTRAINT fk_sx_sales_deals_policy FOREIGN KEY (tenant_id,commission_policy_id) REFERENCES sx_sales_commission_policies(tenant_id,id),
  CONSTRAINT fk_sx_sales_deals_product FOREIGN KEY (tenant_id,product_id) REFERENCES sx_sales_products(tenant_id,id),
  CONSTRAINT fk_sx_sales_deals_reporter FOREIGN KEY (reported_by_identity_id) REFERENCES sx_identities(id),
  CONSTRAINT fk_sx_sales_deals_approver FOREIGN KEY (approved_by_identity_id) REFERENCES sx_identities(id),
  CONSTRAINT chk_sx_sales_deals_positive_amount CHECK (amount_minor>0),
  CONSTRAINT chk_sx_sales_deals_decision CHECK ((status IN ('pending_approval','void') AND approved_by_identity_id IS NULL AND decided_at IS NULL AND commission_policy_id IS NULL) OR (status='rejected' AND approved_by_identity_id IS NOT NULL AND decided_at IS NOT NULL AND commission_policy_id IS NULL) OR (status='approved' AND approved_by_identity_id IS NOT NULL AND decided_at IS NOT NULL AND commission_policy_id IS NOT NULL)),
  CONSTRAINT chk_sx_sales_deals_leader_requires_manager CHECK (team_leader_membership_id IS NULL OR manager_membership_id IS NOT NULL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE sx_sales_commissions (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
