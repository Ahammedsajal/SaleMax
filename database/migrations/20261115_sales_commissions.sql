CREATE TABLE sx_sales_products (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  code VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  name VARCHAR(191) NOT NULL,
  active TINYINT(1) NOT NULL DEFAULT 1,
  created_by_identity_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_sx_sales_product_tenant_id (tenant_id,id),
  UNIQUE KEY uq_sx_sales_product_code (tenant_id,code),
  CONSTRAINT fk_sx_sales_product_tenant FOREIGN KEY (tenant_id) REFERENCES sx_tenants(id),
  CONSTRAINT fk_sx_sales_product_creator FOREIGN KEY (created_by_identity_id) REFERENCES sx_identities(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE sx_sales_commission_policies (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  version INT UNSIGNED NOT NULL,
  status ENUM('draft','approved','retired') NOT NULL DEFAULT 'draft',
  created_by_identity_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  approved_by_identity_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  approved_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  active_tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_sx_sales_commission_policy_tenant_id (tenant_id,id),
  UNIQUE KEY uq_sx_sales_commission_policy_version (tenant_id,version),
  UNIQUE KEY uq_sx_sales_commission_policy_active (active_tenant_id),
  CONSTRAINT fk_sx_sales_commission_policy_tenant FOREIGN KEY (tenant_id) REFERENCES sx_tenants(id),
  CONSTRAINT fk_sx_sales_commission_policy_creator FOREIGN KEY (created_by_identity_id) REFERENCES sx_identities(id),
  CONSTRAINT fk_sx_sales_commission_policy_approver FOREIGN KEY (approved_by_identity_id) REFERENCES sx_identities(id),
  CONSTRAINT chk_sx_sales_commission_policy_active CHECK ((status='approved' AND active_tenant_id=tenant_id) OR (status<>'approved' AND active_tenant_id IS NULL)),
  CONSTRAINT chk_sx_sales_commission_policy_approval CHECK ((status IN ('approved','retired') AND approved_by_identity_id IS NOT NULL AND approved_at IS NOT NULL) OR (status='draft' AND approved_by_identity_id IS NULL AND approved_at IS NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE sx_sales_commission_policy_rates (
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  policy_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  product_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  agent_rate_bps SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  team_leader_rate_bps SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  manager_rate_bps SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (tenant_id,policy_id,product_id),
  CONSTRAINT fk_sx_sales_policy_rate_policy FOREIGN KEY (tenant_id,policy_id) REFERENCES sx_sales_commission_policies(tenant_id,id),
  CONSTRAINT fk_sx_sales_policy_rate_product FOREIGN KEY (tenant_id,product_id) REFERENCES sx_sales_products(tenant_id,id),
  CONSTRAINT chk_sx_sales_policy_rate_split CHECK (agent_rate_bps<=10000 AND team_leader_rate_bps<=10000 AND manager_rate_bps<=10000 AND agent_rate_bps+team_leader_rate_bps+manager_rate_bps<=10000)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE sx_sales_deals (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
