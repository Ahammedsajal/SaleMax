-- Private Real Estate v3: scheduled viewings link existing tenant leads and listings.
-- Times are UTC; no invitations or external messages are sent by this module.
CREATE TABLE sx_real_estate_viewings (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  legacy_uid_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  lead_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  property_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  requirement_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  assigned_membership_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  starts_at_utc DATETIME(3) NOT NULL,
  ends_at_utc DATETIME(3) NOT NULL,
  status ENUM('scheduled','completed','cancelled','no_show') NOT NULL DEFAULT 'scheduled',
  outcome ENUM('interested','follow_up','declined','leased_or_purchased','unknown') NULL,
  notes VARCHAR(500) NOT NULL DEFAULT '',
  revision INT UNSIGNED NOT NULL DEFAULT 1,
  created_by_identity_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  updated_by_identity_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_sx_real_estate_viewing_tenant_id (tenant_id,id),
  KEY idx_sx_real_estate_viewing_slot (tenant_id,property_id,status,starts_at_utc,ends_at_utc),
  KEY idx_sx_real_estate_viewing_member (tenant_id,assigned_membership_id,status,starts_at_utc),
  KEY idx_sx_real_estate_viewing_lead (tenant_id,legacy_uid_hash,lead_id,status,starts_at_utc),
  CONSTRAINT fk_sx_real_estate_viewing_tenant FOREIGN KEY (tenant_id) REFERENCES sx_tenants(id),
  CONSTRAINT fk_sx_real_estate_viewing_property FOREIGN KEY (tenant_id,property_id) REFERENCES sx_real_estate_properties(tenant_id,id),
  CONSTRAINT fk_sx_real_estate_viewing_requirement FOREIGN KEY (tenant_id,requirement_id) REFERENCES sx_real_estate_requirements(tenant_id,id),
  CONSTRAINT fk_sx_real_estate_viewing_assignee FOREIGN KEY (tenant_id,assigned_membership_id) REFERENCES sx_memberships(tenant_id,id),
  CONSTRAINT fk_sx_real_estate_viewing_created_by FOREIGN KEY (tenant_id,created_by_identity_id) REFERENCES sx_memberships(tenant_id,identity_id),
  CONSTRAINT fk_sx_real_estate_viewing_updated_by FOREIGN KEY (tenant_id,updated_by_identity_id) REFERENCES sx_memberships(tenant_id,identity_id),
  CONSTRAINT ck_sx_real_estate_viewing_duration CHECK (ends_at_utc > starts_at_utc AND TIMESTAMPDIFF(MINUTE,starts_at_utc,ends_at_utc) BETWEEN 15 AND 480),
  CONSTRAINT ck_sx_real_estate_viewing_revision CHECK (revision > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
