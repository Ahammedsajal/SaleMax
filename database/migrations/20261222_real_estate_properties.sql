-- First-party real-estate contract. The category stays non-planable until the
-- workflow and role acceptance gates are complete.
CREATE TABLE sx_real_estate_properties (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  reference_code VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  title_en VARCHAR(160) NOT NULL,
  title_ar VARCHAR(160) NOT NULL,
  property_type ENUM('apartment','house','villa','townhouse','land','commercial','office','warehouse','other') NOT NULL,
  transaction_type ENUM('sale','rent') NOT NULL,
  status ENUM('draft','active','under_offer','sold','rented','withdrawn','archived') NOT NULL DEFAULT 'draft',
  price_minor BIGINT UNSIGNED NOT NULL,
  currency CHAR(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'QAR',
  area_sqm DECIMAL(12,2) NULL,
  bedrooms SMALLINT UNSIGNED NULL,
  bathrooms SMALLINT UNSIGNED NULL,
  city VARCHAR(100) NOT NULL,
  description_en TEXT NOT NULL,
  description_ar TEXT NOT NULL,
  revision INT UNSIGNED NOT NULL DEFAULT 1,
  created_by_identity_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  updated_by_identity_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_sx_real_estate_tenant_id (tenant_id,id),
  UNIQUE KEY uq_sx_real_estate_reference (tenant_id,reference_code),
  KEY idx_sx_real_estate_inventory (tenant_id,status,transaction_type,property_type,updated_at),
  KEY idx_sx_real_estate_city (tenant_id,city,status),
  CONSTRAINT fk_sx_real_estate_tenant FOREIGN KEY (tenant_id) REFERENCES sx_tenants(id),
  CONSTRAINT fk_sx_real_estate_created_by FOREIGN KEY (created_by_identity_id) REFERENCES sx_identities(id),
  CONSTRAINT fk_sx_real_estate_updated_by FOREIGN KEY (updated_by_identity_id) REFERENCES sx_identities(id),
  CONSTRAINT fk_sx_real_estate_created_membership FOREIGN KEY (tenant_id,created_by_identity_id) REFERENCES sx_memberships(tenant_id,identity_id),
  CONSTRAINT fk_sx_real_estate_updated_membership FOREIGN KEY (tenant_id,updated_by_identity_id) REFERENCES sx_memberships(tenant_id,identity_id),
  CONSTRAINT ck_sx_real_estate_price CHECK (price_minor <= 999999999999),
  CONSTRAINT ck_sx_real_estate_area CHECK (area_sqm IS NULL OR area_sqm > 0),
  CONSTRAINT ck_sx_real_estate_revision CHECK (revision > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
