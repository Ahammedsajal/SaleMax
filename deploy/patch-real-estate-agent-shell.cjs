'use strict';
const fs=require('node:fs');
const file=process.argv[2];
if(!file)throw Error('SHELL_PATH_REQUIRED');
const reference=/team-invitations\.js\?v=[^"'\s>]+/g;
const after='team-invitations.js?v=20261028-real-estate-ui-sync1';
const cssReference=/team-access\.css\?v=[^"'\s>]+/g;
const cssAfter='team-access.css?v=20261028-team-ui-sync2';
const helper='<script defer src="/team-ui-preferences.js?v=20261028-team-ui-sync1"></script>';
let html=fs.readFileSync(file,'utf8');
const matches=html.match(reference)||[];
if(matches.length!==1)throw Error('REAL_ESTATE_TEAM_SHELL_ANCHOR');
const cssMatches=html.match(cssReference)||[];
if(cssMatches.length!==1)throw Error('REAL_ESTATE_TEAM_CSS_SHELL_ANCHOR');
html=html.replace(reference,after);
html=html.replace(cssReference,cssAfter);
html=html.replace(/<script defer(?:="defer")? src="\/team-ui-preferences\.js\?v=[^" ]+"><\/script>/g,'');
const teamTag=/<script\b[^>]*src="\/?team-invitations\.js\?v=20261028-real-estate-ui-sync1"[^>]*><\/script>/;
if(!teamTag.test(html))throw Error('REAL_ESTATE_TEAM_SCRIPT_ANCHOR');
html=html.replace(teamTag,match=>`${helper}${match}`);
fs.writeFileSync(file,html);
